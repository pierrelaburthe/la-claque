/** Projette une coordonnée géographique dans le repère du fond de carte. */
export const projeter = (lat: number, lon: number): { x: number; y: number } => {
  const b = CARTE.bounds;
  return {
    x: ((lon - b.minLon) * b.kx * b.W) / b.spanX,
    y: b.H - ((lat - b.minLat) * b.H) / b.spanY,
  };
};
